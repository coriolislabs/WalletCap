// spec/schema.sql and spec/upgrade.sql, at the repository's root, are the one copy of the
// ledger's rule. The build compiles them into the package as string constants
// (src/core/_spec.generated.ts, which tsc then builds), so nothing reads them from disk at run
// time and a bundler carries them along. It also copies the files to dist/spec/, for readers.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const from = new URL('../../../spec/', import.meta.url);
const sql = name => readFileSync(new URL(name, from), 'utf8');

writeFileSync(
  new URL('../src/core/_spec.generated.ts', import.meta.url),
  [
    '// SPDX-License-Identifier: Apache-2.0',
    '// Generated by scripts/gen-spec.mjs from spec/schema.sql and spec/upgrade.sql. Do not edit.',
    `export const SCHEMA_SQL = ${JSON.stringify(sql('schema.sql'))};`,
    `export const UPGRADE_SQL = ${JSON.stringify(sql('upgrade.sql'))};`,
    '',
  ].join('\n'),
);

const to = new URL('../dist/spec/', import.meta.url);
mkdirSync(to, { recursive: true });
for (const name of ['schema.sql', 'upgrade.sql']) copyFileSync(new URL(name, from), new URL(name, to));
